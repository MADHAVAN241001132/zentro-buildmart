export class CheckoutError extends Error {}

export interface CheckoutInput {
  customerName: string;
  customerMobile: string;
  customerEmail: string | null;
  method: 'online' | 'cash';
  /** Two-digit GST state code of the place of supply (the customer's state). Checked by the database. */
  supplyStateCode: string;
  /** Per checkout attempt, generated by the form. Repeats of the same key replay the first result. */
  requestKey: string;
}

export interface PlacedOrder {
  orderId: string;
  orderNumber: string;
  method: 'online' | 'cash';
  replayed: boolean;
}

interface PlacementRow {
  order_id: string;
  order_number: string;
  method: 'online' | 'cash';
  replayed: boolean;
  payment_attached: boolean;
}

/** Refusals raised inside guest_checkout_place, mapped to messages the Guest can act on. */
function placementRefusal(message: string): CheckoutError | null {
  if (message.includes('cart_changed')) return new CheckoutError('Your cart changed. Review it and place the order again.');
  if (message.includes('insufficient_stock')) return new CheckoutError('Some items just sold out. Please review your cart.');
  if (message.includes('cart_empty')) return new CheckoutError('Your cart is empty');
  if (message.includes('request_key_reused')) {
    return new CheckoutError('Your details changed after this order was submitted. Please place the order again.');
  }
  if (message.includes('checkout_in_progress')) {
    return new CheckoutError('This order is already being placed. Please wait a moment and check your orders.');
  }
  if (message.includes('coupon')) return new CheckoutError(message.replace(/^.*?: /, ''));
  if (message.includes('gst_profile_incomplete')) {
    return new CheckoutError('This showroom is not able to take orders right now. Please contact the showroom.');
  }
  if (message.includes('pricing_mode_unsupported')) {
    return new CheckoutError('Online and showroom orders with tax-inclusive prices are not available yet. Please contact the showroom.');
  }
  if (message.includes('gst_composition_interstate')) {
    return new CheckoutError('This showroom can only deliver within its own state. Please choose its state.');
  }
  if (message.includes('place of supply')) {
    return new CheckoutError('Choose the state where the order will be delivered.');
  }
  if (message.includes('session has expired')) return new CheckoutError('Your session has expired. Please reload the store.');
  if (message.includes('not taking orders')) return new CheckoutError('This showroom is not taking orders right now');
  return null;
}

/**
 * Places a Guest order in one database transaction (guest_checkout_place, migration 0049).
 * The database claims the request key, locks the cart, verifies the plan against live prices, GST rates and
 * stock, redeems the coupon, reserves stock and records cash. Any failure rolls all of it back.
 * Online payments are created after that commit: the provider order is created outside the transaction and then
 * attached with guest_checkout_attach_payment. A failed provider call leaves the order unpaid with its reservation,
 * which the payment-expiry job releases; the provider call is never repeated automatically.
 */
export async function placeOrder(store: StoreInfo, session: GuestSession, input: CheckoutInput): Promise<PlacedOrder> {
  // New guest orders need an active subscription or a current allowance (see 0031).
  const commerceBlocked = await checkCommerce(store.id);
  if (commerceBlocked) throw new CheckoutError(commerceBlocked);
  if (input.method === 'online' && !store.paymentSettings.onlineEnabled) {
    throw new CheckoutError('Online payment is not available at this showroom');
  }
  if (input.method === 'cash' && !store.paymentSettings.cashEnabled) {
    throw new CheckoutError('Pay-at-showroom is not available at this showroom');
  }
  if (!/^[A-Za-z0-9_-]{8,80}$/.test(input.requestKey)) {
    throw new CheckoutError('Please reload the checkout page and try again');
  }

  const cart = await getCartView(store.id, session.id);
  if (!cart.cartId || cart.lines.length === 0 || !cart.totals) {
    throw new CheckoutError('Your cart is empty');
  }
  for (const line of cart.lines) {
    if (Math.ceil(line.quantity) > line.availableUnits) {
      throw new CheckoutError(`Not enough stock for ${line.productName}. Please update your cart.`);
    }
  }
  if (cart.coupon?.error) {
    throw new CheckoutError(`Coupon ${cart.coupon.code}: ${cart.coupon.error}`);
  }

  const totals = cart.totals;
  const expiresAt = new Date(Date.now() + store.paymentSettings.paymentExpiryMinutes * 60_000).toISOString();
  const plan = {
    method: input.method,
    customer_name: input.customerName,
    customer_mobile: input.customerMobile,
    customer_email: input.customerEmail,
    coupon_code: cart.coupon?.code ?? null,
    supply_state_code: input.supplyStateCode,
    subtotal_paise: totals.subtotalPaise,
    discount_paise: totals.discountPaise,
    tax_paise: totals.taxPaise,
    total_paise: totals.totalPaise,
    expires_at: expiresAt,
    lines: cart.lines.map((line) => {
      const priced = totals.lines.find((t) => t.key === line.itemId);
      if (!priced) throw new CheckoutError('Your cart changed. Review it and place the order again.');
      return {
        variant_id: line.variantId,
        quantity: line.quantity,
        unit_price_paise: line.unitPricePaise,
        cost_price_paise: line.costPricePaise,
        gst_rate_bps: line.gstRateBps,
        product_name: line.productName,
        variant_label: line.variantLabel,
        sku: line.sku,
        hsn_code: line.hsnCode,
        discount_paise: priced.lineDiscountPaise,
        taxable_paise: priced.lineTaxablePaise,
        tax_paise: priced.lineTaxPaise,
        line_total_paise: priced.lineTotalPaise,
      };
    }),
  };

  const admin = createSupabaseAdminClient();
  const { data, error } = await admin.rpc('guest_checkout_place', {
    p_store: store.id,
    p_session: session.id,
    p_request_key: input.requestKey,
    p_plan: plan,
  });
  if (error) {
    throw placementRefusal(error.message) ?? new CheckoutError('We could not place your order. Please try again.');
  }
  const row = data as PlacementRow;
  const placed: PlacedOrder = {
    orderId: row.order_id,
    orderNumber: row.order_number,
    method: row.method,
    replayed: row.replayed,
  };
  if (row.method === 'cash') return placed;
  await initialiseOnlinePayment(admin, store.id, placed.orderId, placed.orderNumber, totals.totalPaise, false);
  return placed;
}

/** Refusals and ambiguous outcomes from the payment provider, each mapped to a Guest message. */
const PAYMENT_START_FAILED = 'We could not start the payment. Your order is saved; open it from your orders to continue.';
const PAYMENT_CONFIRMING = 'We are confirming the payment start with our provider. Please check your order shortly. Do not pay twice.';

/**
 * Durable provider initialisation (migration 0050). The claim is recorded before any provider call, so an interrupted
 * or repeated request can see the outcome. The provider is called only on a fresh claim; an uncertain outcome is never
 * repeated automatically. A created provider order is attached in a separate step, so a failed attach keeps the order id.
 */
async function initialiseOnlinePayment(
  admin: ReturnType<typeof createSupabaseAdminClient>,
  storeId: string,
  orderId: string,
  orderNumber: string,
  amountPaise: number,
  userRetry: boolean,
): Promise<void> {
  const provider = paymentMode() === 'razorpay' ? 'razorpay' : 'simulator';
  const { data: claimData, error: claimError } = await admin.rpc('guest_payment_init_claim', {
    p_order: orderId,
    p_provider: provider,
    p_user_retry: userRetry,
  });
  if (claimError) throw new CheckoutError(PAYMENT_START_FAILED);
  const claim = claimData as { action: string; init_id?: string };

  switch (claim.action) {
    case 'attached':
      return;
    case 'attach':
      return attachInitialised(admin, claim.init_id as string);
    case 'busy':
      throw new CheckoutError(PAYMENT_CONFIRMING);
    case 'uncertain':
      throw new CheckoutError(PAYMENT_CONFIRMING);
    case 'refused':
      throw new CheckoutError('Our payment provider did not accept this order. Please place the order again.');
    case 'review':
    case 'closed':
      throw new CheckoutError('This order can no longer take a payment. Please contact the showroom.');
    case 'call':
      break;
    default:
      throw new CheckoutError(PAYMENT_START_FAILED);
  }

  const initId = claim.init_id as string;
  let providerOrderId: string;
  let providerAmount: number;
  let providerCurrency: string;
  try {
    if (provider === 'razorpay') {
      const order = await createRazorpayOrder({
        amountPaise,
        receipt: orderNumber,
        notes: { store_id: storeId, order_id: orderId },
      });
      providerOrderId = order.id;
      providerAmount = order.amount;
      providerCurrency = order.currency;
    } else {
      providerOrderId = `sim_order_${orderId}`;
      providerAmount = amountPaise;
      providerCurrency = 'INR';
    }
  } catch (error) {
    // Only an explicit provider rejection before creation is a refusal; everything else is reconciled, never retried.
    const refused = classifyProviderFailure(error) === 'refused';
    await admin.rpc('guest_payment_init_finish', {
      p_init: initId,
      p_outcome: refused ? 'refused' : 'uncertain',
      p_provider_order_id: null,
      p_amount_paise: null,
      p_currency: null,
      p_safe_detail: safeProviderDetail(error),
    });
    throw new CheckoutError(refused ? 'Our payment provider did not accept this order. Please place the order again.' : PAYMENT_CONFIRMING);
  }

  const { data: finishData, error: finishError } = await admin.rpc('guest_payment_init_finish', {
    p_init: initId,
    p_outcome: 'created',
    p_provider_order_id: providerOrderId,
    p_amount_paise: providerAmount,
    p_currency: providerCurrency,
    p_safe_detail: null,
  });
  if (finishError) throw new CheckoutError(PAYMENT_CONFIRMING);
  const finish = finishData as { action: string };
  if (finish.action === 'amount_mismatch') throw new CheckoutError('This payment needs review by the showroom.');
  if (finish.action !== 'created') throw new CheckoutError(PAYMENT_CONFIRMING);
  await attachInitialised(admin, initId);
}

async function attachInitialised(admin: ReturnType<typeof createSupabaseAdminClient>, initId: string): Promise<void> {
  const { data, error } = await admin.rpc('guest_payment_init_attach', { p_init: initId });
  if (error || (data as { action?: string } | null)?.action !== 'attached') {
    // The provider order id is stored; the next claim attaches it without a second provider call.
    throw new CheckoutError(PAYMENT_START_FAILED);
  }
}

export interface GuestOrderView {
  orderId: string;
  orderNumber: string;
  method: 'online' | 'cash' | 'credit';
  paymentStatus: string;
  orderStatus: string;
  customerName: string;
  customerMobile: string | null;
  subtotalPaise: number;
  discountPaise: number;
  taxPaise: number;
  totalPaise: number;
  createdAt: string;
  paidAt: string | null;
  items: {
    productName: string;
    variantLabel: string;
    quantity: number;
    lineTotalPaise: number;
  }[];
  razorpayKeyId: string | null;
  providerOrderId: string | null;
  provider: string | null;
  reservationExpiresAt: string | null;
  /** The single state the Guest sees (lib/payments/guest-payment-state.ts). */
  paymentState: GuestPaymentState;
}

/** Order for the guest who placed it. Matches on the guest session, never on the order number alone. */
export async function getGuestOrder(storeId: string, sessionId: string, orderNumber: string): Promise<GuestOrderView | null> {
  const admin = createSupabaseAdminClient();
  const { data: order, error } = await admin
    .from('orders')
    .select(
      `id, order_number, payment_method, payment_status, order_status, customer_name, customer_mobile, subtotal_paise,
       discount_paise, tax_paise, total_paise, created_at, paid_at, reservation_expires_at,
       order_items(product_name_snapshot, variant_label_snapshot, quantity, line_total_paise)`,
    )
    .eq('store_id', storeId)
    .eq('guest_session_id', sessionId)
    .eq('order_number', orderNumber)
    .maybeSingle();
  if (error) throw new Error('Could not load order');
  if (!order) return null;

  const { data: payment } = await admin
    .from('payments')
    .select('provider, provider_order_id')
    .eq('order_id', order.id as string)
    .order('created_at', { ascending: false })
    .limit(1)
    .maybeSingle();
  const [{ data: init }, { data: lates }, { data: refunds }] = await Promise.all([
    admin.from('payment_initialisations').select('status').eq('order_id', order.id as string).maybeSingle(),
    admin.from('late_payments').select('status').eq('order_id', order.id as string),
    admin.from('refunds').select('refund_type, status, gateway_state').eq('order_id', order.id as string),
  ]);
  const paymentState = guestPaymentState(paymentFactsFromRows({
    order: {
      payment_method: order.payment_method as string,
      order_status: order.order_status as string,
      payment_status: order.payment_status as string,
      reservation_expires_at: (order.reservation_expires_at as string | null) ?? null,
    },
    payment: payment ? { provider_order_id: (payment.provider_order_id as string | null) ?? null } : null,
    init: init ? { status: init.status as string } : null,
    lates: (lates ?? []).map((l: Record<string, unknown>) => ({ status: l.status as string })),
    refunds: (refunds ?? []).map((r: Record<string, unknown>) => ({
      refund_type: (r.refund_type as string | null) ?? null,
      status: r.status as string,
      gateway_state: r.gateway_state as string,
    })),
  }));

  const items = (order.order_items ?? []) as {
    product_name_snapshot: string;
    variant_label_snapshot: string;
    quantity: number;
    line_total_paise: number;
  }[];
  return {
    orderId: order.id as string,
    orderNumber: order.order_number as string,
    method: order.payment_method as 'online' | 'cash' | 'credit',
    paymentStatus: order.payment_status as string,
    orderStatus: order.order_status as string,
    customerName: order.customer_name as string,
    customerMobile: (order.customer_mobile as string | null) ?? null,
    subtotalPaise: order.subtotal_paise as number,
    discountPaise: order.discount_paise as number,
    taxPaise: order.tax_paise as number,
    totalPaise: order.total_paise as number,
    createdAt: order.created_at as string,
    paidAt: (order.paid_at as string | null) ?? null,
    items: items.map((i) => ({
      productName: i.product_name_snapshot,
      variantLabel: i.variant_label_snapshot,
      quantity: i.quantity,
      lineTotalPaise: i.line_total_paise,
    })),
    razorpayKeyId:
      payment?.provider === 'razorpay' ? (process.env.NEXT_PUBLIC_RAZORPAY_KEY_ID ?? process.env.RAZORPAY_KEY_ID ?? null) : null,
    providerOrderId: (payment?.provider_order_id as string | undefined) ?? null,
    provider: (payment?.provider as string | undefined) ?? null,
    reservationExpiresAt: (order.reservation_expires_at as string | null) ?? null,
    paymentState,
  };
}

/**
 * Starts a new provider payment for a Guest whose previous start was definitively refused. The database accepts a
 * user retry only in that state; any other state (including uncertain) is refused here and in the database.
 */
export async function retryOnlinePayment(storeId: string, sessionId: string, orderNumber: string): Promise<void> {
  const order = await getGuestOrder(storeId, sessionId, orderNumber);
  if (!order) throw new CheckoutError('This order could not be found.');
  if (!order.paymentState.canRetry) throw new CheckoutError('A new payment cannot be started for this order right now.');
  const admin = createSupabaseAdminClient();
  await initialiseOnlinePayment(admin, storeId, order.orderId, order.orderNumber, order.totalPaise, true);
}
